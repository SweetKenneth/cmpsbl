  '  capability: string,',
  '  defender: (input: Record<string, unknown>) => unknown,',
  '): CmpsblWargameResult {',
  '  let passed = 0;',
  '  const failedSamples: string[] = [];',
  '  for (const sample of _CMPSBL_WARGAME_CORPUS) {',
