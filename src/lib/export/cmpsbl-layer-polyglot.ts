  '            CmpsblCircuitState::Open => { self.opened_at = Some(Self::now_ms()); self.consecutive_successes = 0; }',
  '            CmpsblCircuitState::Closed => { self.failures = 0; self.current_timeout_ms = self.timeout_ms; }',
