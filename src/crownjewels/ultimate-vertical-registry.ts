export function getUltimateJewelsByPrimitive(primitiveId: string): STierEntry[] {
  return ULTIMATE_CROWN_JEWELS.filter(j => j.module === primitiveId);
}

export function getUltimateJewelSummary(): Array<{
  primitive: string; count: number; avgCjpi: number; topJewel: string;
}> {
  const primitives = [...new Set(ULTIMATE_CROWN_JEWELS.map(j => j.module))];
  return primitives.map(p => {
    const jewels = ULTIMATE_CROWN_JEWELS.filter(j => j.module === p);
    const top = jewels.reduce((a, b) => a.cjpi > b.cjpi ? a : b);
    return {
      primitive: p,
      count: jewels.length,
      avgCjpi: Math.round(jewels.reduce((s, j) => s + j.cjpi, 0) / jewels.length * 10) / 10,
      topJewel: top.name,
    };
  });
}
